// @ts-check
// docs/decisions/README.md: every decision record in one table, and the records
// that amend the v1 scope (0009) in another, so "is this in v1?" is one file and
// not 29. Generated from the records' own headers; the README is never edited.
//
//   node tooling/gen-decisions-index.mjs           write the README
//   node tooling/gen-decisions-index.mjs --check   fail when it is stale (CI, pre-push)

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./lib/repo.mjs";

const DIR = "docs/decisions";
const SCOPE = "0009";

/**
 * @typedef {object} Record
 * @property {string} number four digits
 * @property {string} file
 * @property {string} title
 * @property {string} status the first clause of the Status bullet
 * @property {string} statusFull the whole Status bullet
 * @property {string} date
 */

/**
 * @param {string} file name such as `0009-v1-scope.md`
 * @param {string} text
 * @returns {Record}
 */
export function parseRecord(file, text) {
  const number = file.slice(0, 4);
  const title = new RegExp(`^# ${number}\\. (.+)$`, "m").exec(text)?.[1]?.trim();
  const statusFull = /^- Status: (.+)$/m.exec(text)?.[1]?.trim();
  const date = /^- Date: (\d{4}-\d{2}-\d{2})\b/m.exec(text)?.[1];
  if (!title || !statusFull || !date) {
    throw new Error(
      `${DIR}/${file}: needs a "# ${number}. Title" heading and Status and Date bullets`,
    );
  }
  return { number, file, title, status: statusFull.split(";")[0]?.trim() ?? "", statusFull, date };
}

/**
 * The records that amend the v1 scope: the numbers after "amended by" in the
 * Status of 0009, which is the list the scope record keeps.
 *
 * @param {Record[]} records
 * @returns {string[]}
 */
export function amendersOfScope(records) {
  const scope = records.find((r) => r.number === SCOPE);
  if (!scope) throw new Error(`${DIR}: no record ${SCOPE}`);
  const clause = /amended by (.*)$/.exec(scope.statusFull)?.[1] ?? "";
  return [...new Set([...clause.matchAll(/\b(\d{4})\b/g)].map((m) => m[1] ?? ""))];
}

/** @param {string} text */
const cell = (text) => text.replaceAll("|", "\\|");

/**
 * A pipe table with padded columns, the shape the formatter leaves alone.
 *
 * @param {string[]} head
 * @param {string[][]} rows
 */
function table(head, rows) {
  const widths = head.map((h, i) => Math.max(h.length, ...rows.map((r) => (r[i] ?? "").length)));
  const line = (/** @type {string[]} */ cols) =>
    `| ${cols.map((c, i) => c.padEnd(widths[i] ?? 0)).join(" | ")} |`;
  return [
    line(head),
    `| ${widths.map((w) => "-".repeat(w)).join(" | ")} |`,
    ...rows.map(line),
  ].join("\n");
}

/**
 * @param {Record[]} records sorted by number
 * @returns {string} the README text
 */
export function render(records) {
  const link = (/** @type {Record} */ r) => `[${r.number}](${r.file})`;
  const amenders = new Set(amendersOfScope(records));
  const scoped = records
    .filter((r) => amenders.has(r.number))
    .sort((a, b) => a.date.localeCompare(b.date) || a.number.localeCompare(b.number));
  const scope = /** @type {Record} */ (records.find((r) => r.number === SCOPE));
  return [
    "# Decision records",
    "",
    "<!-- Generated by tooling/gen-decisions-index.mjs from the records in this directory. Do not edit. -->",
    "",
    "Generated from the Status and Date bullets of each record. The rules for writing one are in",
    "AGENTS.md § Decision records.",
    "",
    "## v1 scope",
    "",
    `${link(scope)} sets what the first release holds. The ${scoped.length} records below amend it, oldest first;`,
    "a feature outside 0009 and outside this list needs a new record before it is built.",
    "",
    table(
      ["Record", "Date", "Amends the scope of v1 by"],
      scoped.map((r) => [link(r), r.date, cell(r.title)]),
    ),
    "",
    "## All records",
    "",
    table(
      ["Record", "Title", "Status", "Date"],
      records.map((r) => [link(r), cell(r.title), cell(r.status), r.date]),
    ),
    "",
  ].join("\n");
}

/**
 * @param {string} [root]
 * @returns {Record[]}
 */
export function readRecords(root = ROOT) {
  return readdirSync(join(root, DIR))
    .filter((f) => /^\d{4}-.+\.md$/.test(f))
    .sort()
    .map((f) => parseRecord(f, readFileSync(join(root, DIR, f), "utf8")));
}

function main() {
  const out = join(ROOT, DIR, "README.md");
  const text = render(readRecords());
  if (process.argv.includes("--check")) {
    if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
      console.error(`✗ ${DIR}/README.md is stale: run node tooling/gen-decisions-index.mjs`);
      process.exit(1);
    }
    console.log(`✓ ${DIR}/README.md is current (${text.split("\n").length} lines)`);
    return;
  }
  writeFileSync(out, text);
  console.log(`wrote ${DIR}/README.md`);
}

if (import.meta.main) main();
