// @ts-check
// Emits the limits every client shares with the server from api/limits.json
// (decision 0123), one file per language, so a number has one place to change.
//
// `node tooling/limits-gen.mjs`          write the files
// `node tooling/limits-gen.mjs --check`  fail when one is stale (CI, pre-push)

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { readJson, ROOT } from "./lib/repo.mjs";

const SOURCE = "api/limits.json";
const HEADER = `Generated by tooling/limits-gen.mjs from ${SOURCE}. Do not edit.`;

/**
 * @typedef {object} Limit
 * @property {string} name lower camel case
 * @property {"chars" | "count" | "page" | "bytes" | "days"} unit
 * @property {number} value
 * @property {string} doc
 */

/** The type of each unit where the language has more than one integer. */
const RUST_TYPES = { chars: "usize", count: "usize", page: "u32", bytes: "u64", days: "u32" };
const KOTLIN_SUFFIX = { chars: "", count: "", page: "", bytes: "L", days: "" };

/**
 * Refuses a source that would generate something wrong, or nothing.
 *
 * @param {unknown} source
 * @returns {Limit[]}
 */
export function parse(source) {
  const limits = /** @type {{ limits?: Limit[] }} */ (source).limits;
  if (!Array.isArray(limits) || limits.length === 0) throw new Error(`${SOURCE}: no limits`);
  const names = new Set();
  for (const limit of limits) {
    if (!/^[a-z][a-zA-Z0-9]*$/.test(limit.name)) {
      throw new Error(`${SOURCE}: ${limit.name} is not lower camel case`);
    }
    if (names.has(limit.name)) throw new Error(`${SOURCE}: ${limit.name} appears twice`);
    names.add(limit.name);
    if (!(limit.unit in RUST_TYPES)) throw new Error(`${SOURCE}: ${limit.name} has no known unit`);
    if (!Number.isSafeInteger(limit.value) || limit.value < 1) {
      throw new Error(`${SOURCE}: ${limit.name} is not a positive whole number`);
    }
    if (!limit.doc) throw new Error(`${SOURCE}: ${limit.name} says nothing about itself`);
  }
  return limits;
}

/** @param {string} name */
function constant(name) {
  return name.replace(/[A-Z]/g, (letter) => `_${letter}`).toUpperCase();
}

/**
 * A number with a separator every three digits, which Rust, Kotlin and Swift all read.
 *
 * @param {number} value
 */
function grouped(value) {
  return String(value).replace(/\B(?=(\d{3})+$)/g, "_");
}

/** @param {Limit[]} limits */
export function typescript(limits) {
  const rows = limits.map((l) => `  /** ${l.doc} */\n  ${l.name}: ${l.value},\n`).join("");
  return `// ${HEADER}\nexport const LIMITS = {\n${rows}} as const;\n`;
}

/** @param {Limit[]} limits */
export function rust(limits) {
  const rows = limits.map(
    (l) =>
      `/// ${l.doc}\npub const ${constant(l.name)}: ${RUST_TYPES[l.unit]} = ${grouped(l.value)};\n`,
  );
  return `// ${HEADER}\n\n${rows.join("\n")}`;
}

/** @param {Limit[]} limits */
export function kotlin(limits) {
  const rows = limits.map(
    (l) =>
      `    /** ${l.doc} */\n    const val ${constant(l.name)} = ${grouped(l.value)}${KOTLIN_SUFFIX[l.unit]}\n`,
  );
  return `// ${HEADER}\npackage samtak.spjall.limits\n\nobject Limits {\n${rows.join("\n")}}\n`;
}

/** @param {Limit[]} limits */
export function swift(limits) {
  const rows = limits.map(
    (l) => `    /// ${l.doc}\n    nonisolated static let ${l.name} = ${grouped(l.value)}\n`,
  );
  return `// ${HEADER}\n\nenum Limits {\n${rows.join("\n")}}\n`;
}

/**
 * Every file and what it should hold.
 *
 * @param {Limit[]} limits
 * @returns {Record<string, string>}
 */
export function outputs(limits) {
  return {
    "backend/src/limits.gen.ts": typescript(limits),
    "web/src/generated/limits.ts": typescript(limits),
    "core/client/src/generated/limits.rs": rust(limits),
    "android/app/src/generated/kotlin/samtak/spjall/limits/Limits.kt": kotlin(limits),
    "ios/App/generated/Limits.swift": swift(limits),
  };
}

/**
 * The files that differ from what the source says.
 *
 * @param {Record<string, string>} wanted
 * @param {(path: string) => string | null} read the committed text, null when it is missing
 * @returns {string[]}
 */
export function stale(wanted, read) {
  return Object.entries(wanted)
    .filter(([path, text]) => read(path) !== text)
    .map(([path]) => path);
}

/** @param {string} path */
function committed(path) {
  const file = join(ROOT, path);
  return existsSync(file) ? readFileSync(file, "utf8") : null;
}

function main() {
  const wanted = outputs(parse(readJson(SOURCE)));
  if (process.argv.includes("--check")) {
    const behind = stale(wanted, committed);
    for (const path of behind) {
      console.error(`❌ ${path} is stale. Run \`node tooling/limits-gen.mjs\` and commit it.`);
    }
    if (behind.length > 0) process.exit(1);
    console.log(`✓ ${Object.keys(wanted).length} files match ${SOURCE}`);
    return;
  }
  for (const [path, text] of Object.entries(wanted)) {
    mkdirSync(dirname(join(ROOT, path)), { recursive: true });
    writeFileSync(join(ROOT, path), text);
  }
}

if (import.meta.main) main();
