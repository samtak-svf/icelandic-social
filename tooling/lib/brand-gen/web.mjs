// @ts-check
// Web outputs of the brand, all under web/src/generated/brand/ (decision 0062): the
// strings as a typed module, the tokens as Tailwind theme variables with a
// dark mode, the bundled fonts with their licences, and the icons.

import { brandColors, fontFamilies, hex2, radii } from "./color.mjs";
import { renderOpaquePng, squareFrame } from "./icon.mjs";
import { keysFor } from "./strings.mjs";

/**
 * @typedef {import("./strings.mjs").BrandInput} BrandInput
 * @typedef {import("./strings.mjs").ContractKey} ContractKey
 * @typedef {import("./strings.mjs").OutputFile} OutputFile
 */

const DIR = "web/src/generated/brand";

/** @param {{ r: number, g: number, b: number, a: number }} c */
function hex(c) {
  return `#${hex2(c.r)}${hex2(c.g)}${hex2(c.b)}${c.a < 255 ? hex2(c.a) : ""}`.toLowerCase();
}

/**
 * A sentence as a TypeScript expression: literal text joined to `args.<name>`
 * for each placeholder. Literals go through JSON.stringify, so no sentence
 * can break out of its string.
 *
 * @param {string} text
 * @param {ContractKey} spec
 */
function expression(text, spec) {
  const names = Object.keys(spec.placeholders ?? {});
  /** @type {string[]} */
  const parts = [];
  let last = 0;
  for (const match of text.matchAll(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g)) {
    const name = /** @type {string} */ (match[1]);
    if (!names.includes(name)) throw new Error(`placeholder {${name}} is not declared`);
    if (match.index > last) parts.push(JSON.stringify(text.slice(last, match.index)));
    parts.push(spec.placeholders?.[name] === "int" ? `String(args.${name})` : `args.${name}`);
    last = match.index + match[0].length;
  }
  if (last < text.length || parts.length === 0) parts.push(JSON.stringify(text.slice(last)));
  return parts.join(" + ");
}

/**
 * One key as a property: a plain string, or a function of its placeholders.
 * A plural chooses its sentence by Icelandic CLDR rules from `count`.
 *
 * @param {string} key
 * @param {ContractKey} spec
 * @param {import("./strings.mjs").StringValue | undefined} value
 */
function entry(key, spec, value) {
  const placeholders = Object.entries(spec.placeholders ?? {});
  const doc = `  /** ${spec.description} */`;
  if (typeof value === "string" && placeholders.length === 0)
    return [doc, `  ${key}: ${JSON.stringify(value)},`];
  const params = placeholders
    .map(([name, type]) => `${name}: ${type === "int" ? "number" : "string"}`)
    .join("; ");
  const head = `  ${key}: (args: { ${params} }): string =>`;
  if (typeof value === "string") return [doc, head, `    ${expression(value, spec)},`];
  if (spec.placeholders?.count !== "int")
    throw new Error(`${key}: a plural needs an int placeholder named count`);
  const forms = value ?? {};
  return [
    doc,
    head,
    `    plural.select(args.count) === "one"`,
    `      ? ${expression(forms.one ?? "", spec)}`,
    `      : ${expression(forms.other ?? "", spec)},`,
  ];
}

/** @param {BrandInput} brand */
function stringsModule(brand) {
  const keys = keysFor(brand.contract, "web");
  const entries = keys.flatMap(([key, spec]) => entry(key, spec, brand.strings[key]));
  const plurals = keys.some(([, spec]) => spec.plural)
    ? ['const plural = new Intl.PluralRules("is");', ""]
    : [];
  return [
    `// Generated by tooling/brand-gen.mjs from brand/${brand.name}/strings.is.json. Do not edit;`,
    "// run `pnpm brand:gen`.",
    "",
    ...plurals,
    "export const strings = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");
}

/** @param {string} family */
function cssFamily(family) {
  return /^[a-z-]+$/.test(family) ? family : JSON.stringify(family);
}

/**
 * The tokens as Tailwind theme variables (`bg-primary`, `font-headline`,
 * `rounded-md`). Tailwind's own palette, families and radii are cleared, so a
 * class can only name a brand token, and every variable is emitted, used or
 * not, so the dark mode overrides a full set when the system asks for it
 * (decision 0052).
 *
 * @param {BrandInput} brand
 */
function themeCss(brand) {
  const light = brandColors(brand.tokens);
  const dark = brandColors(brand.tokens, "dark");
  const families = fontFamilies(brand.tokens);
  const fallbacks = Object.fromEntries(
    Object.entries(brand.tokens.font ?? {}).map(([name, token]) => [
      name,
      /** @type {any} */ (token).$value?.slice?.(1) ?? [],
    ]),
  );
  const faces = brand.fonts.flatMap((font) => {
    const family = families.find((f) => f.name === font.family)?.family ?? font.family;
    return [
      "@font-face {",
      `  font-family: ${cssFamily(family)};`,
      `  font-weight: ${font.weight};`,
      "  font-display: swap;",
      `  src: url("./fonts/${font.fileName}") format("truetype");`,
      "}",
      "",
    ];
  });
  return [
    `/* Generated by tooling/brand-gen.mjs from brand/${brand.name}/tokens.json. Do not edit;`,
    "   run `pnpm brand:gen`. */",
    "",
    "@theme static {",
    "  --color-*: initial;",
    "  --font-*: initial;",
    "  --radius-*: initial;",
    ...light.map((c) => `  --color-${c.name}: ${hex(c)};`),
    ...families.map(
      (f) =>
        `  --font-${f.name}: ${[f.family, ...(fallbacks[f.name] ?? [])].map(cssFamily).join(", ")};`,
    ),
    ...radii(brand.tokens).map((r) => `  --radius-${r.name}: ${r.value}px;`),
    "}",
    "",
    "@layer base {",
    "  @media (prefers-color-scheme: dark) {",
    "    :root {",
    ...dark.map((c) => `      --color-${c.name}: ${hex(c)};`),
    "    }",
    "  }",
    "}",
    "",
    ...faces,
  ].join("\n");
}

/**
 * The font files, and each licence beside them.
 *
 * @param {BrandInput} brand
 * @returns {OutputFile[]}
 */
function fontFiles(brand) {
  /** @type {Map<string, OutputFile>} */
  const files = new Map();
  for (const font of brand.fonts) {
    files.set(font.fileName, { path: `${DIR}/fonts/${font.fileName}`, content: font.bytes });
    files.set(font.licenseName, {
      path: `${DIR}/fonts/${font.licenseName}`,
      content: `${font.license.trimEnd()}\n`,
    });
  }
  return [...files.values()];
}

/**
 * The favicon as an SVG on the icon's background, with rounded corners, and
 * the PNG a phone's home screen asks for, opaque on the same background.
 *
 * @param {BrandInput} brand
 * @returns {OutputFile[]}
 */
function icons(brand) {
  const color = brandColors(brand.tokens).find((c) => c.name === brand.manifest.icon.background);
  const background = color ? `#${hex2(color.r)}${hex2(color.g)}${hex2(color.b)}` : "#000000";
  const framed = squareFrame(brand.iconSvg);
  const favicon = framed.replace(
    /<svg\b[^>]*>/,
    (open) =>
      `${open}\n  <rect x="15" y="15" width="78" height="78" rx="17" fill="${background}"/>`,
  );
  return [
    { path: `${DIR}/favicon.svg`, content: favicon },
    { path: `${DIR}/apple-touch-icon.png`, content: renderOpaquePng(framed, 180, background) },
  ];
}

/**
 * @param {BrandInput} brand
 * @returns {OutputFile[]}
 */
export function web(brand) {
  return [
    { path: `${DIR}/strings.ts`, content: stringsModule(brand) },
    { path: `${DIR}/theme.css`, content: themeCss(brand) },
    ...fontFiles(brand),
    ...icons(brand),
  ];
}
