// @ts-check
// iOS outputs of the brand, all under ios/Generated/: the xcconfigs the
// project includes, the string catalog, the token enum, the bundled fonts
// with their licences, the app icon, the accent colour and a colour set per
// token with its dark appearance.

import { brandColors, fontFamilies, hex2, radii } from "./color.mjs";
import { postScriptName } from "./font-name.mjs";
import { renderOpaquePng, squareFrame } from "./icon.mjs";
import { camel, keysFor, positional } from "./strings.mjs";

/**
 * @typedef {import("./strings.mjs").BrandInput} BrandInput
 * @typedef {import("./strings.mjs").OutputFile} OutputFile
 */

const DIR = "ios/Generated";
const XCODE_INFO = { author: "xcode", version: 1 };

/**
 * @param {number} position
 * @param {string} type
 */
function specifier(position, type) {
  return `%${position}$${type === "int" ? "lld" : "@"}`;
}

/** @param {unknown} value */
function json(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

/**
 * The font files under their own names, and each licence beside them.
 *
 * @param {BrandInput} brand
 * @returns {OutputFile[]}
 */
function fontFiles(brand) {
  /** @type {Map<string, OutputFile>} */
  const files = new Map();
  for (const font of brand.fonts) {
    files.set(font.fileName, {
      path: `${DIR}/Fonts/${font.fileName}`,
      content: font.bytes,
    });
    files.set(font.licenseName, {
      path: `${DIR}/Fonts/${font.licenseName}`,
      content: `${font.license.trimEnd()}\n`,
    });
  }
  return [...files.values()];
}

/**
 * A sentence as an xcconfig value. xcconfig has no quoting: `//` starts a
 * comment and `$(` a substitution, so a sentence holding either is refused.
 *
 * @param {unknown} value
 */
function xcconfigValue(value) {
  if (typeof value !== "string" || value.includes("//") || value.includes("$(")) {
    throw new Error(`not a plain sentence for an xcconfig value: ${JSON.stringify(value)}`);
  }
  return value;
}

/** @param {BrandInput} brand */
function xcconfig(brand) {
  const hosts = [brand.ids.hosts.link, ...brand.manifest.aliasHosts];
  return [
    `// Generated by tooling/brand-gen.mjs from brand/${brand.name}/. Do not edit; run`,
    "// `pnpm brand:gen`. No DEVELOPMENT_TEAM here: the team is a frozen id",
    "// (identifiers/ids.json), not part of the brand.",
    "",
    `INFOPLIST_KEY_CFBundleDisplayName = ${brand.manifest.displayName}`,
    `INFOPLIST_KEY_NSCameraUsageDescription = ${xcconfigValue(brand.strings.camera_usage)}`,
    `INFOPLIST_KEY_NSLocationWhenInUseUsageDescription = ${xcconfigValue(brand.strings.location_usage)}`,
    "ASSETCATALOG_COMPILER_APPICON_NAME = AppIcon",
    `BRAND_ASSOCIATED_DOMAINS = ${hosts.map((h) => `applinks:${h}`).join(" ")}`,
    "",
  ].join("\n");
}

/**
 * The frozen ids Xcode needs, so project.yml names none of them. Not brand
 * data, but generated here so the same --check holds it to ids.json. A null
 * Apple team (decision 0010) leaves DEVELOPMENT_TEAM empty: debug builds run
 * unsigned and a release build cannot be signed.
 *
 * @param {BrandInput} brand
 */
function idsXcconfig(brand) {
  const { store, hosts, services } = brand.ids;
  return [
    "// Generated by tooling/brand-gen.mjs from identifiers/ids.json. Do not edit;",
    "// run `pnpm brand:gen`.",
    "",
    `SPJALL_BUNDLE_ID = ${store.iosBundleId}`,
    `SPJALL_NSE_BUNDLE_ID = ${store.iosNotificationServiceBundleId}`,
    `SPJALL_APP_GROUP = ${store.appGroup}`,
    `SPJALL_URL_SCHEME = ${store.urlScheme}`,
    `SPJALL_API_HOST = ${hosts.api}`,
    `SPJALL_WEB_HOST = ${hosts.web}`,
    `DEVELOPMENT_TEAM = ${services.appleTeamId ?? ""}`,
    "",
  ].join("\n");
}

/**
 * The Interim configuration's overrides (decision 0011): TestFlight builds on
 * another organisation's team carry the interim ids, never the frozen ones.
 * Written only while ids.json has an interim; without these files the Interim
 * configuration has no team and cannot sign. Profile names follow the bundle
 * ids, so the workflow, Xcode and the export options agree without a list.
 *
 * @param {BrandInput} brand
 * @returns {OutputFile[]}
 */
function interimFiles(brand) {
  const interim = brand.ids.appleInterim;
  if (!interim) return [];
  const appProfile = profileName(interim.iosBundleId);
  const nseProfile = profileName(interim.iosNotificationServiceBundleId);
  const overrides = [
    "// Generated by tooling/brand-gen.mjs from identifiers/ids.json (appleInterim,",
    "// decision 0011). Do not edit; run `pnpm brand:gen`. Included by the Interim",
    "// configuration only, after Ids.xcconfig.",
    "",
    `SPJALL_BUNDLE_ID = ${interim.iosBundleId}`,
    `SPJALL_NSE_BUNDLE_ID = ${interim.iosNotificationServiceBundleId}`,
    `SPJALL_APP_GROUP = ${interim.appGroup}`,
    `DEVELOPMENT_TEAM = ${interim.teamId}`,
    `SPJALL_APP_PROFILE = ${appProfile}`,
    `SPJALL_NSE_PROFILE = ${nseProfile}`,
    "",
  ].join("\n");
  const plist = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    "<!-- Generated by tooling/brand-gen.mjs from identifiers/ids.json (appleInterim). Do not edit. -->",
    '<plist version="1.0">',
    "<dict>",
    "\t<key>method</key>",
    "\t<string>app-store-connect</string>",
    "\t<key>teamID</key>",
    `\t<string>${interim.teamId}</string>`,
    "\t<key>signingStyle</key>",
    "\t<string>manual</string>",
    "\t<key>provisioningProfiles</key>",
    "\t<dict>",
    `\t\t<key>${interim.iosBundleId}</key>`,
    `\t\t<string>${appProfile}</string>`,
    `\t\t<key>${interim.iosNotificationServiceBundleId}</key>`,
    `\t\t<string>${nseProfile}</string>`,
    "\t</dict>",
    "</dict>",
    "</plist>",
    "",
  ].join("\n");
  return [
    { path: `${DIR}/IdsInterim.xcconfig`, content: overrides },
    { path: `${DIR}/ExportOptions.Interim.plist`, content: plist },
  ];
}

/**
 * The App Store provisioning profile name for a bundle id. The profiles on the
 * interim team are registered under exactly this name (docs/store-accounts/).
 *
 * @param {string} bundleId
 */
function profileName(bundleId) {
  return `${bundleId} appstore`;
}

/** @param {BrandInput} brand */
function stringCatalog(brand) {
  /** @type {Record<string, unknown>} */
  const strings = {};
  for (const [key, spec] of keysFor(brand.contract, "ios")) {
    const value = brand.strings[key];
    /** @param {string} text */
    const unit = (text) => ({
      stringUnit: {
        state: "translated",
        value: positional(text, spec, specifier),
      },
    });
    const localization =
      typeof value === "string"
        ? unit(value)
        : {
            variations: {
              plural: Object.fromEntries(
                Object.entries(value ?? {}).map(([category, text]) => [category, unit(text)]),
              ),
            },
          };
    strings[key] = {
      comment: spec.description,
      extractionState: "manual",
      localizations: { is: localization },
    };
  }
  return json({ sourceLanguage: "is", strings, version: "1.0" });
}

/** @param {BrandInput} brand */
function tokensSwift(brand) {
  /** @param {string | undefined} text */
  const doc = (text) => (text ? [`        /// ${text}`] : []);
  const dark = brandColors(brand.tokens, "dark");
  const colors = brandColors(brand.tokens).flatMap((c, i) => [
    ...doc(c.description),
    `        static let ${camel(c.name)} = Color("${COLOR_NAMESPACE}/${c.name}", bundle: .main) // ${hexA(c)}, dark ${hexA(dark[i] ?? c)}`,
  ]);
  const fonts = fontFamilies(brand.tokens).map(
    (f) => `        static let ${camel(f.name)} = "${f.family}"`,
  );
  const type = "[(file: String, name: String, weight: Int)]";
  const faces = fontFamilies(brand.tokens).flatMap((f) => {
    const list = brand.fonts
      .filter((font) => font.family === f.name)
      .map(
        (font) =>
          `            ("${font.fileName}", "${postScriptName(font.bytes)}", ${font.weight}),`,
      );
    return list.length === 0
      ? [`        static let ${camel(f.name)}: ${type} = []`]
      : [`        static let ${camel(f.name)}: ${type} = [`, ...list, "        ]"];
  });
  const radius = radii(brand.tokens).map(
    (r) => `        static let ${camel(r.name)}: CGFloat = ${r.value}`,
  );
  return [
    `// Generated by tooling/brand-gen.mjs from brand/${brand.name}/tokens.json. Do not edit;`,
    "// run `pnpm brand:gen`.",
    "",
    "import SwiftUI",
    "",
    "enum BrandTokens {",
    "    /// The catalog's colour sets (Assets.xcassets/Brand), each with a dark",
    "    /// appearance, so a colour follows the system's mode (decision 0052).",
    "    enum Colors {",
    ...colors,
    "",
    "        /// Every colour by its token name, for the tests that hold each to its set.",
    "        static let all: [String: Color] = [",
    ...brandColors(brand.tokens).map((c) => `            "${c.name}": ${camel(c.name)},`),
    "        ]",
    "    }",
    "",
    "    /// Font family names, as the design names them.",
    "    enum Fonts {",
    ...fonts,
    "    }",
    "",
    "    /// Each family's bundled faces: the file in Fonts/, the PostScript name",
    "    /// iOS finds it by, and its weight. An empty list means the family is",
    "    /// not bundled and the system font stands in. The licences travel in",
    "    /// Fonts/ beside the files.",
    "    enum FontFiles {",
    ...faces,
    "    }",
    "",
    "    enum Radius {",
    ...radius,
    "    }",
    "}",
    "",
  ].join("\n");
}

/** @param {BrandInput} brand */
function appIcon(brand) {
  const color = brandColors(brand.tokens).find((c) => c.name === brand.manifest.icon.background);
  const background = color ? `#${hex2(color.r)}${hex2(color.g)}${hex2(color.b)}` : "#000000";
  const set = `${DIR}/Assets.xcassets/AppIcon.appiconset`;
  return [
    {
      path: `${DIR}/Assets.xcassets/Contents.json`,
      content: json({ info: XCODE_INFO }),
    },
    {
      path: `${set}/Contents.json`,
      content: json({
        images: [
          {
            filename: "AppIcon-1024.png",
            idiom: "universal",
            platform: "ios",
            size: "1024x1024",
          },
        ],
        info: XCODE_INFO,
      }),
    },
    {
      path: `${set}/AppIcon-1024.png`,
      content: renderOpaquePng(squareFrame(brand.iconSvg), 1024, background),
    },
  ];
}

/** @param {{ r: number, g: number, b: number, a: number }} c */
function hexA(c) {
  return `#${hex2(c.r)}${hex2(c.g)}${hex2(c.b)}${c.a < 255 ? hex2(c.a) : ""}`;
}

/** @param {{ r: number, g: number, b: number, a: number }} c */
function catalogColor(c) {
  const component = (/** @type {number} */ byte) => `0x${hex2(byte)}`;
  return {
    "color-space": "srgb",
    components: {
      alpha: (c.a / 255).toFixed(3),
      blue: component(c.b),
      green: component(c.g),
      red: component(c.r),
    },
  };
}

/**
 * A colour set: the light colour, and the dark one for the dark appearance.
 *
 * @param {{ r: number, g: number, b: number, a: number }} light
 * @param {{ r: number, g: number, b: number, a: number }} dark
 */
function colorSet(light, dark) {
  return json({
    colors: [
      { color: catalogColor(light), idiom: "universal" },
      {
        appearances: [{ appearance: "luminosity", value: "dark" }],
        color: catalogColor(dark),
        idiom: "universal",
      },
    ],
    info: XCODE_INFO,
  });
}

/** The catalog folder the token colours live in, and the prefix of their names. */
const COLOR_NAMESPACE = "Brand";

/**
 * One colour set per token, under a namespace so no name meets the system's
 * own (`primary`, `secondary`).
 *
 * @param {BrandInput} brand
 * @returns {OutputFile[]}
 */
function colorSets(brand) {
  const folder = `${DIR}/Assets.xcassets/${COLOR_NAMESPACE}`;
  const dark = brandColors(brand.tokens, "dark");
  return [
    {
      path: `${folder}/Contents.json`,
      content: json({ info: XCODE_INFO, properties: { "provides-namespace": true } }),
    },
    ...brandColors(brand.tokens).map((light, i) => ({
      path: `${folder}/${light.name}.colorset/Contents.json`,
      content: colorSet(light, dark[i] ?? light),
    })),
  ];
}

/**
 * The catalog's AccentColor, the brand's primary, which the project names as
 * the app's global accent so system controls never fall back to their blue.
 *
 * @param {BrandInput} brand
 * @returns {OutputFile}
 */
function accentColor(brand) {
  const light = brandColors(brand.tokens).find((c) => c.name === "primary");
  const dark = brandColors(brand.tokens, "dark").find((c) => c.name === "primary");
  if (!light || !dark) throw new Error("tokens have no primary colour for the accent");
  return {
    path: `${DIR}/Assets.xcassets/AccentColor.colorset/Contents.json`,
    content: colorSet(light, dark),
  };
}

/**
 * @param {BrandInput} brand
 * @returns {OutputFile[]}
 */
export function ios(brand) {
  return [
    { path: `${DIR}/Brand.xcconfig`, content: xcconfig(brand) },
    { path: `${DIR}/Ids.xcconfig`, content: idsXcconfig(brand) },
    ...interimFiles(brand),
    { path: `${DIR}/Localizable.xcstrings`, content: stringCatalog(brand) },
    { path: `${DIR}/BrandTokens.swift`, content: tokensSwift(brand) },
    ...fontFiles(brand),
    ...appIcon(brand),
    accentColor(brand),
    ...colorSets(brand),
  ];
}
